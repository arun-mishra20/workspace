export function applyOklchColorTokens(
  presetName: string,
  preset: ThemePreset,
): ThemePreset {
  const oklchColors = EXPRESSIVE_OKLCH_COLORS[presetName]
  if (!oklchColors) {
    return preset
  }

  return {
    light: { ...preset.light, ...oklchColors.light },
    dark: { ...preset.dark, ...oklchColors.dark },
  }
}
